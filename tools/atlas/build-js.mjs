// Writes js/atlas/atlas-data.js: one generated JS copy of the Atlas JSON (categories, views, core pack,
// category packs, records, prices), the desk lineup and the community lane, so the app runs from
// a local server, from file:// and on a static host with no fetch. Do not hand-edit the output.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT, J, JR, CATEGORY_PACKS } from "./lib.mjs";
import { readFileSync } from "node:fs";

// Coarse ISO 3166-1 alpha-2 -> alpha-3 for the bundled world outline (Natural Earth a3). Only codes in use.
const A3 = { US: "USA", GB: "GBR", IT: "ITA", IN: "IND", FR: "FRA", MU: "MUS" };

export function buildData() {
  const entries = CATEGORY_PACKS.flatMap((p) => J(`packs/${p}/entries.json`).entries);
  const manifests = Object.fromEntries(["core", ...CATEGORY_PACKS].map((id) => {
    const m = J(`packs/${id}/manifest.json`);
    return [id, { id, title: m.title, version: m.version, status: m.status, entry_count: m.entry_count, size_bytes: m.size_bytes, refresh: m.refresh, sha256: m.sha256 }];
  }));
  const records = {};
  entries.forEach((e) => [e.record, ...(e.records || [])].filter(Boolean).forEach((r) => { records[r] = JR(r); }));
  const places = J("packs/core/places.json");
  places.places.forEach((p) => { const c = p.key.slice(0, 2); p.a3 = A3[c] || "[UNKNOWN]"; p.parent = p.key.length > 2 ? c : null; });
  return {
    schema: "globedesk.atlas-bundle/1",
    generated: J("packs/core/index.json").generated,
    categories: J("categories.json").categories,
    views: J("views.json"),
    index: J("packs/core/index.json").entries,
    entries,
    sources: J("packs/core/sources.json").sources,
    places,
    years: J("packs/core/years.json"),
    manifests,
    records,
    desks: JR("desks/work-desks.json"),
    community: J("community/community.json"),
    openItems: (readFileSync(path.join(ROOT, "atlas", "OPEN-ITEMS.md"), "utf8").match(/^\| \d+ \|/gm) || []).length,
  };
}

export const OUT = path.join(ROOT, "js", "atlas", "atlas-data.js");
export function render(data) {
  return "/* Generated by tools/atlas/build-js.mjs from atlas/, data/atlas/ and desks/. Do not edit by hand. */\n" +
    "(window.GD = window.GD || {}).atlasData = " + JSON.stringify(data) + ";\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUT, render(buildData()));
  console.log("wrote js/atlas/atlas-data.js");
}
