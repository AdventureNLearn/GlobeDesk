#!/usr/bin/env python3
"""Build the Ancient World polity outlines from a local copy of Cliopatria (Seshat Global History Databank, CC BY 4.0).

Input : a Cliopatria GeoJSON (cliopatria.geojson from the repository's cliopatria.geojson.zip), passed as argv[1].
Output: js/atlas/ancient-extents-data.js  (window.GD.ancientExtents = FeatureCollection, loaded only when the
        outline layer is switched on) and data/atlas/ancient/extents-index.json (years, counts, sha256, credit).

Changes made to the source (CC BY 4.0 asks us to say so): POLITY features only (RELATION rows dropped); one
snapshot per year in YEARS keeps the polities whose FromYear <= year <= ToYear; shapes simplified with
shapely (tolerance 0.05 degrees, topology preserved) and rounded to 0.01 degrees; fields kept: Name, FromYear,
ToYear, Wikidata. Borders are approximate. Needs shapely (not a runtime dependency; build-time only).
"""
import hashlib, json, os, sys
from shapely.geometry import shape, mapping
from shapely import set_precision

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
YEARS = [-3000, -2500, -2000, -1500, -1000, -500, -200, 1, 200, 500, 800, 1000, 1200, 1400]
TOL, GRID = 0.05, 0.01
COMMIT = "04b4e06bb4cce4f4834a057efbd23d4453619256"
# Attribution line as approved (Analyst verdict 2026-11-26). Do not reword.
ATTRIBUTION = "Polity borders: Cliopatria, Seshat Global History Databank (https://github.com/Seshat-Global-History-Databank/cliopatria), CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Subset; borders simplified and approximate; changes by GlobeDesk."
AUTHORS = "[UNKNOWN] (the repository files at this commit carry no author list)"

def label(y):
    return f"{-y} BCE" if y < 0 else f"{y} CE"

def main(src):
    d = json.load(open(src, encoding="utf-8"))
    polities = [f for f in d["features"] if f["properties"].get("Type") == "POLITY"]
    feats, counts = [], {}
    for y in YEARS:
        n = 0
        for f in sorted(polities, key=lambda f: f["properties"]["Name"]):
            p = f["properties"]
            if not (p["FromYear"] <= y <= p["ToYear"]):
                continue
            g = set_precision(shape(f["geometry"]).simplify(TOL, preserve_topology=True), GRID)
            if g.is_empty:
                continue
            feats.append({"type": "Feature", "properties": {"name": p["Name"], "year": y, "from": p["FromYear"], "to": p["ToYear"], "wikidata": p.get("Wikidata") or None},
                          "geometry": mapping(g)})
            n += 1
        counts[str(y)] = n
    fc = {"type": "FeatureCollection", "approximate": True,
          "credit": ATTRIBUTION,
          "features": feats}
    body = json.dumps(fc, separators=(",", ":"), ensure_ascii=False)
    js = "/* Generated by tools/atlas/build-ancient-extents.py from Cliopatria (CC BY 4.0). Do not edit by hand. */\n(window.GD = window.GD || {}).ancientExtents = " + body + ";\n"
    out = os.path.join(ROOT, "js", "atlas", "ancient-extents-data.js")
    open(out, "w", encoding="utf-8").write(js)
    sha = hashlib.sha256(js.encode("utf-8")).hexdigest()
    index = {
        "schema": "globedesk.ancient-extents/1", "id": "ancient-extents", "title": "Approximate polity outlines (Cliopatria)",
        "file": "js/atlas/ancient-extents-data.js", "bytes": len(js.encode("utf-8")), "sha256": sha,
        "years": [{"year": y, "label": label(y), "polities": counts[str(y)]} for y in YEARS],
        "feature_count": len(feats), "approximate": True,
        "source": {"id": "cliopatria", "commit": COMMIT, "license": "CC BY 4.0", "license_url": "https://creativecommons.org/licenses/by/4.0/", "url": "https://github.com/Seshat-Global-History-Databank/cliopatria", "authors": AUTHORS},
        "attribution": ATTRIBUTION,
        "year_convention": "Snapshot years follow Cliopatria (negative = BCE, so -3000 is 3000 BCE), not the Atlas's astronomical years.",
        "changes": "POLITY features only; one snapshot per listed year; simplified (0.05 degree tolerance) and rounded to 0.01 degrees; fields kept: name, from, to, wikidata.",
        "limits": ["Borders are approximate: Cliopatria says its maps reflect one version of past territory and that border uncertainties are common.",
                   "Coverage starts in 3400 BCE, so outlines for earlier sites such as Göbekli Tepe are [UNKNOWN].",
                   "No outline covers Caral, Great Zimbabwe, or Teotihuacan before 1000 CE: a gap in the dataset, not evidence that no state existed."],
        "checked": "2026-11-26", "license": "CC BY 4.0 (derived from Cliopatria; credit required)",
    }
    os.makedirs(os.path.join(ROOT, "data", "atlas", "ancient"), exist_ok=True)
    open(os.path.join(ROOT, "data", "atlas", "ancient", "extents-index.json"), "w", encoding="utf-8").write(json.dumps(index, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {len(feats)} outlines over {len(YEARS)} years, {len(js)} bytes")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: build-ancient-extents.py <cliopatria.geojson>")
    main(sys.argv[1])
